// Extracts the product strings of the design page (`L.tr` and `L.en`) into
// locales/design/<lang>.ftl, so translations are never copied by hand (docs/PLAN.md M2).
//
//   node tools/extract-locales.js            write locales/design/*.ftl
//   node tools/extract-locales.js --check    fail if they are out of date
//
// Key naming: camelCase keys become kebab-case (`lPlaceholder` → `l-placeholder`);
// objects add the member (`looks.a` → `looks-a`, `accents["#8fd3ff"]` → `accents-8fd3ff`);
// arrays add the index (`days[1]` → `days-1`, `keys[0][1]` → `keys-0-1`); functions become
// messages with a `$value` variable; HTML tags are dropped.
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.resolve(__dirname, "..");
const page = path.join(root, "docs", "design", "kabuk-tasarim.html");
const outDir = path.join(root, "locales", "design");
const SENTINEL = "\u0000VALUE\u0000";

function dictionaries(html) {
  const start = html.indexOf("const L = {");
  if (start < 0) throw new Error("`const L = {` not found in the design page");
  // Walk to the matching closing brace, skipping strings and template literals.
  let i = html.indexOf("{", start), depth = 0, quote = null;
  for (; i < html.length; i++) {
    const c = html[i];
    if (quote) {
      if (c === "\\") { i++; continue; }
      if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") quote = c;
    else if (c === "{") depth++;
    else if (c === "}" && --depth === 0) break;
  }
  const source = html.slice(html.indexOf("{", start), i + 1);
  return vm.runInNewContext(`(${source})`);
}

const kebab = (k) => String(k).replace(/^#/, "").replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase().replace(/[^a-z0-9-]/g, "-");

function escapeFtl(text) {
  // Fluent: braces are syntax; a leading [, * or . would start a variant or attribute.
  return text.replace(/[{}]/g, (b) => `{"${b}"}`).replace(/^([\[*.])/, '{"$1"}');
}

function flatten(prefix, value, out) {
  if (typeof value === "function") {
    const text = String(value(SENTINEL)).replace(/<[^>]+>/g, "");
    out.push([prefix, escapeFtl(text).split(SENTINEL).join("{ $value }")]);
  } else if (Array.isArray(value)) {
    value.forEach((v, i) => flatten(`${prefix}-${i}`, v, out));
  } else if (value && typeof value === "object") {
    for (const [k, v] of Object.entries(value)) flatten(`${prefix}-${kebab(k)}`, v, out);
  } else {
    out.push([prefix, escapeFtl(String(value).replace(/<[^>]+>/g, ""))]);
  }
}

function render(lang, dict) {
  const entries = [];
  for (const [k, v] of Object.entries(dict)) flatten(kebab(k), v, entries);
  const lines = entries.map(([k, v]) => `${k} = ${v}`);
  return `## Generated by tools/extract-locales.js from docs/design/kabuk-tasarim.html (L.${lang}). Do not edit by hand.\n\n${lines.join("\n")}\n`;
}

function main() {
  const check = process.argv.includes("--check");
  const L = dictionaries(fs.readFileSync(page, "utf8"));
  const langs = Object.keys(L);
  if (!langs.includes("tr") || !langs.includes("en")) throw new Error("L.tr and L.en expected");
  const stale = [];
  if (!check) fs.mkdirSync(outDir, { recursive: true });
  for (const lang of langs) {
    const file = path.join(outDir, `${lang}.ftl`);
    const text = render(lang, L[lang]);
    if (check) {
      const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : "";
      if (cur !== text) stale.push(path.relative(root, file));
    } else {
      fs.writeFileSync(file, text);
    }
  }
  if (check && stale.length) {
    console.error(`out of date (run node tools/extract-locales.js): ${stale.join(", ")}`);
    process.exit(1);
  }
  console.log(check ? "locales up to date" : `wrote ${langs.join(", ")} to ${path.relative(root, outDir)}`);
}

main();
