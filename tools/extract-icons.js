// Extracts the icon <symbol>s of the design page into assets/icons/<name>.svg.
//
//   node tools/extract-icons.js            write assets/icons/*.svg
//   node tools/extract-icons.js --check    fail if assets/icons is out of date
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const page = path.join(root, "docs", "design", "kabuk-tasarim.html");
const outDir = path.join(root, "assets", "icons");

function icons(html) {
  const out = [];
  for (const m of html.matchAll(/<symbol id="i-([a-z0-9-]+)" viewBox="([^"]+)">([\s\S]*?)<\/symbol>/g)) {
    out.push({ name: m[1], viewBox: m[2], body: m[3].trim() });
  }
  if (!out.length) throw new Error("no icon symbols found in the design page");
  return out;
}

function svg(icon) {
  return (
    `<!-- Generated by tools/extract-icons.js from docs/design/kabuk-tasarim.html. Do not edit by hand. -->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${icon.viewBox}" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round">${icon.body}</svg>\n`
  );
}

function main() {
  const check = process.argv.includes("--check");
  const list = icons(fs.readFileSync(page, "utf8"));
  const expected = new Set(list.map((i) => `${i.name}.svg`));
  const stale = [];
  if (!check) fs.mkdirSync(outDir, { recursive: true });
  for (const icon of list) {
    const file = path.join(outDir, `${icon.name}.svg`);
    const text = svg(icon);
    if (check) {
      const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : "";
      if (current !== text) stale.push(path.relative(root, file));
    } else {
      fs.writeFileSync(file, text);
    }
  }
  const extra = fs.existsSync(outDir) ? fs.readdirSync(outDir).filter((f) => f.endsWith(".svg") && !expected.has(f)) : [];
  if (check && (stale.length || extra.length)) {
    console.error(`icons out of date (run node tools/extract-icons.js): ${[...stale, ...extra].join(", ")}`);
    process.exit(1);
  }
  if (!check) extra.forEach((f) => fs.unlinkSync(path.join(outDir, f)));
  console.log(check ? "icons up to date" : `wrote ${list.length} icons to ${path.relative(root, outDir)}`);
}

main();
