// Extracts the colour and size tokens of the seven looks from the design page into
// themes/<code>.toml, so nothing is copied by hand (docs/PLAN.md M2).
//
//   node tools/extract-themes.js            write themes/*.toml
//   node tools/extract-themes.js --check    fail if themes/*.toml are out of date
//
// Token layering follows the page's CSS cascade:
//   dark  = .screen  <-  .screen[data-dir="x"]
//   light = dark     <-  .screen[data-mode="light"]  <-  .screen[data-mode="light"][data-dir="x"]
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const page = path.join(root, "docs", "design", "kabuk-tasarim.html");
const outDir = path.join(root, "themes");
const looks = ["a", "b", "c", "d", "e", "f", "g"];

function styleText(html) {
  const blocks = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]);
  if (!blocks.length) throw new Error("no <style> in the design page");
  return blocks.join("\n").replace(/\/\*[\s\S]*?\*\//g, "");
}

// Custom properties declared by rules whose selector is exactly `selector`, in source order.
function declarations(css, selector) {
  const out = {};
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const selectors = m[1].split(",").map((s) => s.trim().replace(/\s+/g, " "));
    if (!selectors.includes(selector)) continue;
    for (const decl of m[2].split(";")) {
      const d = decl.trim().match(/^--([\w-]+)\s*:\s*([\s\S]+)$/);
      if (d) out[d[1]] = d[2].trim();
    }
  }
  return out;
}

function tomlTable(name, tokens) {
  const keys = Object.keys(tokens).sort();
  return `[${name}]\n` + keys.map((k) => `${k} = ${JSON.stringify(tokens[k])}`).join("\n") + "\n";
}

// Rıhtım's dock tiles: `.dock .a1 { background: linear-gradient(#top, #bottom) }` becomes
// `dock-a1 = "linear-gradient(#top, #bottom)"`, only for a look that shows the dock.
function dockTiles(css, look) {
  if (!css.includes(`.screen[data-dir="${look}"] .dock {`)) return {};
  const out = {};
  for (const m of css.matchAll(/\.dock \.(a\d+)\s*\{\s*background:\s*(linear-gradient\([^)]*\))\s*;?\s*\}/g)) {
    out[`dock-${m[1]}`] = m[2];
  }
  if (!Object.keys(out).length) throw new Error(`look ${look} shows a dock but no tile colours were found`);
  return out;
}

function render(css, look) {
  const base = declarations(css, ".screen");
  const dir = declarations(css, `.screen[data-dir="${look}"]`);
  const light = declarations(css, '.screen[data-mode="light"]');
  const lightDir = declarations(css, `.screen[data-mode="light"][data-dir="${look}"]`);
  if (!Object.keys(base).length) throw new Error("no .screen tokens found");
  if (!Object.keys(dir).length) throw new Error(`no tokens for look ${look}`);
  const dark = { ...base, ...dir, ...dockTiles(css, look) };
  const lightAll = { ...dark, ...light, ...lightDir };
  return (
    "# Generated by tools/extract-themes.js from docs/design/kabuk-tasarim.html. Do not edit by hand.\n" +
    `code = "${look}"\n\n` +
    tomlTable("dark", dark) +
    "\n" +
    tomlTable("light", lightAll)
  );
}

function main() {
  const check = process.argv.includes("--check");
  const css = styleText(fs.readFileSync(page, "utf8"));
  let stale = [];
  if (!check) fs.mkdirSync(outDir, { recursive: true });
  for (const look of looks) {
    const file = path.join(outDir, `${look}.toml`);
    const text = render(css, look);
    if (check) {
      const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : "";
      if (current !== text) stale.push(path.relative(root, file));
    } else {
      fs.writeFileSync(file, text);
    }
  }
  if (check && stale.length) {
    console.error(`out of date (run node tools/extract-themes.js): ${stale.join(", ")}`);
    process.exit(1);
  }
  console.log(check ? "themes up to date" : `wrote ${looks.length} themes to ${path.relative(root, outDir)}`);
}

main();
