// Copies what the settings app takes from the design page, so the settings screen looks
// exactly as designed and is never restyled or redrawn by hand (docs/PLAN.md M8; DECISIONS D3):
//
// - apps/kabuk-settings/ui/design.css: the page's stylesheet;
// - apps/kabuk-settings/ui/design-art.js: the looks' table (default accents, gaps, bar
//   edges), the accent swatches, the theme cards' mini previews, the screen savers'
//   pictures and the wallpaper scenes, as the page's own script draws them.
//
//   node tools/extract-settings.js            write both files
//   node tools/extract-settings.js --check    fail if either is out of date
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const page = path.join(root, "docs", "design", "kabuk-tasarim.html");
const ui = path.join(root, "apps", "kabuk-settings", "ui");
const HEADER = "Generated by tools/extract-settings.js from docs/design/kabuk-tasarim.html. Do not edit by hand.";

function stylesheet(html) {
  const m = html.match(/<style>([\s\S]*?)<\/style>/);
  if (!m) throw new Error("no <style> block in the design page");
  return `/* ${HEADER} */\n` + m[1].replace(/^\n/, "");
}

// The page's source from the line holding `start` up to (not including) the line holding `end`.
function block(html, start, end) {
  const from = html.indexOf(start);
  if (from < 0) throw new Error(`\`${start}\` not found in the design page`);
  const to = html.indexOf(end, from + start.length);
  if (to < 0) throw new Error(`\`${end}\` not found after \`${start}\` in the design page`);
  const lineStart = html.lastIndexOf("\n", from) + 1;
  const lineEnd = html.lastIndexOf("\n", to) + 1;
  return html.slice(lineStart, lineEnd);
}

function art(html) {
  const parts = [
    // looks, lookDefaults, lookGaps, lookPos
    block(html, "const looks = [", "// Design-page copy"),
    block(html, "const accentList = [", "const state = {"),
    // seeded, hashText, motionOK, wallSvg
    block(html, "const seeded = (seed)", "/* A wallpaper id"),
    // miniLook (a-g), saverArt and the system theme's icons (SYS_ICONS, systemIcon)
    block(html, "const miniLook = {", "function dateText"),
  ];
  return `// ${HEADER}
// The page's own drawing code, run with the settings page's \`t\` and \`escapeHtml\`.
"use strict";
window.kabukDesignArt = function (t, escapeHtml) {
${parts.join("")}  return { looks, lookDefaults, lookGaps, lookPos, accentList, hashText, wallSvg, miniLook, saverArt, SYS_ICONS, systemIcon };
};
`;
}

function main() {
  const check = process.argv.includes("--check");
  const html = fs.readFileSync(page, "utf8").replace(/\r\n/g, "\n");
  const outputs = [
    [path.join(ui, "design.css"), stylesheet(html)],
    [path.join(ui, "design-art.js"), art(html)],
  ];
  let stale = false;
  for (const [out, text] of outputs) {
    if (check) {
      const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
      if (current !== text) {
        console.error(`out of date (run node tools/extract-settings.js): ${path.relative(root, out)}`);
        stale = true;
      }
      continue;
    }
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, text);
    console.log(`wrote ${path.relative(root, out)}`);
  }
  if (stale) process.exit(1);
  if (check) console.log("settings files up to date");
}

main();
